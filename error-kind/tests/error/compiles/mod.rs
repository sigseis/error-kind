// -----------------------------------------------------------------------------
macro_rules! assert_alt_err {
    ($actual:expr, $($msg:tt)+) => {
        assert_eq!(format!("{:#}", $actual.unwrap_err()), format!($($msg)*))
    };
}

// -----------------------------------------------------------------------------
macro_rules! assert_err {
    ($actual:expr, $($msg:tt)+) => {
        assert_eq!($actual.unwrap_err().to_string(), format!($($msg)*))
    };
}

// -----------------------------------------------------------------------------
macro_rules! assert_multi_eq {
    ($actual:expr, $($expected:expr),+ $(,)?) => {{
        let actual = $actual;
        $(assert_eq!(actual, $expected);)*
    }};
}

