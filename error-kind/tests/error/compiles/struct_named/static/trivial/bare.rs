// -----------------------------------------------------------------------------
#[derive(Clone, Debug, error_kind::Error, PartialEq)]
struct BareError {
    error_kind: SimpleErrorKind,
}

// -----------------------------------------------------------------------------
impl BareError {
    pub fn new(error_kind: SimpleErrorKind) -> Self {
        Self { error_kind }
    }
    pub fn with_description(error_kind: SimpleErrorKind, _s: impl Into<String>) -> Self {
        Self { error_kind }
    }
}

// -----------------------------------------------------------------------------
#[derive(Clone, Debug, error_kind::Error, PartialEq)]
struct BareErrorAlt {
    #[error_kind]
    error_kind: SimpleErrorKind,
}

